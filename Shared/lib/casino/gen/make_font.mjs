// Turns the old Surface font bitmap into lib/casino/font.lua, so the casino needs no font asset or Surface library.
//   node Shared/lib/casino/gen/make_font.mjs Games/UltimateTicTacToe/font Shared/lib/casino/font.lua
import { readFileSync, writeFileSync } from "node:fs";

const [src, dest] = process.argv.slice(2);
const lines = readFileSync(src, "latin1").replace(/\r/g, "").split("\n");
while (lines.length && lines[lines.length - 1].trim() === "") lines.pop();
const height = lines.length - 1;
const width = Math.max(...lines.map((l) => l.length));
const marks = lines[height].padEnd(width, " ");
// The last row marks where each glyph ends: the first colour that differs from the first cell
const start = marks[0];
const hit = [...marks].find((c) => c !== start);
const cuts = [];
for (let i = 0; i < width; i++) if (marks[i] === hit) cuts.push(i);

const glyphs = [];
let from = 0;
for (const cut of [...cuts, width]) {
  const rows = [];
  for (let y = 0; y < height; y++) {
    const line = lines[y].padEnd(width, " ");
    let row = "";
    for (let x = from; x < cut; x++) row += line[x] !== " " ? "#" : ".";
    rows.push(row);
  }
  glyphs.push(rows);
  from = cut + 1;
}

const out = [
  "-- font.lua",
  "-- Generated by gen/make_font.mjs. The casino's pixel font, printable ASCII from space.",
  "",
  "local M = { HEIGHT = " + height + " }",
  "",
  "local GLYPHS = {",
];
glyphs.forEach((rows, i) => {
  if (i >= 95) return;
  out.push("  { " + rows.map((r) => `"${r}"`).join(", ") + " }, -- " + JSON.stringify(String.fromCharCode(32 + i)));
});
out.push(
  "}",
  "",
  "local cache = {}",
  "",
  "--- The glyph for one character: { width, rows }. Unknown characters draw as a question mark.",
  "function M.glyph(ch)",
  "  local found = cache[ch]",
  "  if found then return found end",
  "  local rows = GLYPHS[ch:byte() - 31] or GLYPHS[32]",
  "  found = { width = #rows[1], rows = rows }",
  "  cache[ch] = found",
  "  return found",
  "end",
  "",
  "--- Width in cells of a string, with one cell between letters.",
  "function M.width(str)",
  "  local total = 0",
  "  for i = 1, #str do",
  "    total = total + M.glyph(str:sub(i, i)).width + 1",
  "  end",
  "  return math.max(0, total - 1)",
  "end",
  "",
  "return M",
  "",
);
writeFileSync(dest, out.join("\n"));
console.log(`${glyphs.length} glyphs, height ${height}`);
